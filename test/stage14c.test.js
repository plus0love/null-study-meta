test('OutdoorWorld 낚시: 자리 앞에서 cast → wait → 입질(bite) → 창 안 reel 성공(저장·이벤트) · 이르면 early · 늦으면 miss · 움직이면 취소 · 하루 5마리 limit · 탑승 불가 · 퇴장 정리', async () => {
  const { world, store, advance, now, settle } = makeOutdoor({ npc: { autoStart: false, random: seeded(42), tickMs: 150 } });
  const p = world.join({ nickname: '민수', socketId: 's1' }).player;
  const ev = [];
  world.on('fishing', (e) => ev.push([e.state, e.result ? (e.result.ok ? 'ok' : e.result.reason) : null]));
  world.on('fishCaught', (e) => ev.push(['caught', e.fish.id, e.rare]));
  const spot = world.room.interactables.find((i) => i.id === 'fish:2');
  assert.equal((await world.cast(p, 9)).error, 'no_spot');
  assert.equal((await world.cast(p, 2)).error, 'too_far');
  p.x = spot.x; p.y = spot.y;
  p.vehicle = { type: 'kart' };
  assert.equal((await world.cast(p, 2)).error, 'riding');
  p.vehicle = null;
  const c1 = await world.cast(p, 2);
  assert.equal(c1.ok, true);
  assert.equal(c1.state, 'wait');
  assert.ok(c1.biteIn >= Fishing.BITE_MIN_MS && c1.biteIn <= Fishing.BITE_MAX_MS);
  assert.deepEqual(world.publicPlayer(p).fishing, { state: 'wait', spot: '2' });
  assert.equal((await world.cast(p, 2)).error, 'already');
  assert.equal((await world.reel(p)).error, 'early');
  assert.equal(world.publicPlayer(p).fishing, null);
  await world.cast(p, 2);
  const s = world.fishing.get(p.id);
  advance(s.biteAt - now() - 1);
  world.tickFishing(now());
  assert.equal(p.fishing.state, 'wait');
  advance(1);
  world.tickFishing(now());
  assert.equal(p.fishing.state, 'bite');
  advance(300);
  const r = await world.reel(p);
  assert.equal(r.ok, true);
  assert.ok(Fishing.fishById(r.fish.id));
  assert.equal(r.left, 4);
  assert.equal((await store.fishCodex('민수')).length, 1);
  await world.cast(p, 2);
  const s2 = world.fishing.get(p.id);
  advance(s2.windowUntil - now() + 1);
  world.tickFishing(now());
  assert.equal(p.fishing, null);
  assert.equal((await world.reel(p)).error, 'not_fishing');
  await world.cast(p, 2);
  p.budget = 10000; p.lastMoveAt = now() - 50;
  advance(100);
  assert.equal(world.move(p, { x: p.x + 20, y: p.y, facing: 'right', moving: true }).ok, true);
  assert.equal(p.fishing, null);
  assert.ok(ev.some((e) => e[1] === 'moved'));
  p.x = spot.x; p.y = spot.y;
  for (let i = 0; i < 4; i++) {
    assert.equal((await world.cast(p, 2)).ok, true);
    const ss = world.fishing.get(p.id);
    advance(ss.biteAt - now() + 100);
    world.tickFishing(now());
    assert.equal((await world.reel(p)).ok, true);
  }
  assert.equal((await world.cast(p, 2)).error, 'limit');
  assert.equal(await store.fishCatchesToday('민수', { tz: 'Asia/Seoul', now: now() }), 5);
  advance(24 * 3600 * 1000);
  assert.equal((await world.cast(p, 2)).ok, true, '다음 날 다시');
  world.endFishing(p);
  assert.equal(ev.filter((e) => e[0] === 'caught').length, 5);
  assert.deepEqual(ev.slice(0, 2), [['wait', null], [null, 'early']]);
  await world.cast(p, 2);
  world.detach(p, 'outdoor');
  assert.equal(world.fishing.size, 0);
  await settle();
  await world.dispose();
});

