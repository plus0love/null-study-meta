const T = 32;
const KST = (iso) => new Date(`${iso}+09:00`).getTime();
const outdoor = getOutdoor();
const quiet = { log() {}, warn() {}, error() {} };

function seeded(seed = 7) {
  let s = seed;
  return () => { s = (s * 1103515245 + 12345) % 2147483648; return s / 2147483648; };
}

function makeOutdoor(opts = {}) {
  let t = KST('2026-09-18T14:00:00');
  const store = opts.store || createMemoryStore();
  const world = new OutdoorWorld(outdoor, { now: () => t, store, tz: 'Asia/Seoul', npc: { autoStart: false, random: seeded(3), tickMs: 150 }, study: { autoTick: false }, log: quiet, ...opts });
  const advance = (ms) => { t += ms; };
  const settle = async () => { await Promise.all([...world.pendingAwards]); };
  return { world, store, advance, settle, now: () => t };
}

test('낚시 규칙: 10종(흔함 6·보통 3·희귀 1) · roll 확률 66/30/4 · 세션(5~10초 입질 → 1.2초 창) · 낚시 자리 4곳·망원경 지점', () => {
  assert.equal(Fishing.FISH.length, 10);
  assert.deepEqual(['common', 'uncommon', 'rare'].map((r) => Fishing.FISH.filter((f) => f.rarity === r).length), [6, 3, 1]);
  assert.equal(new Set(Fishing.FISH.map((f) => f.id)).size, 10);
  const cnt = { common: 0, uncommon: 0, rare: 0 };
  const r = seeded(99);
  for (let i = 0; i < 50000; i++) cnt[Fishing.roll(r).rarity]++;
  assert.ok(Math.abs(cnt.common / 50000 - 0.66) < 0.02 && Math.abs(cnt.uncommon / 50000 - 0.30) < 0.02 && Math.abs(cnt.rare / 50000 - 0.04) < 0.01, JSON.stringify(cnt));
  assert.equal(Fishing.roll(() => 0.999).id, 'golden_carp');
  assert.equal(Fishing.roll(() => 0).id, 'crucian');
  const s = Fishing.newSession('0', 1000, () => 0.5);
  assert.equal(s.biteAt, 1000 + Fishing.BITE_MIN_MS + Math.floor(0.5 * (Fishing.BITE_MAX_MS - Fishing.BITE_MIN_MS)));
  assert.equal(Fishing.tickSession(s, s.biteAt - 1), null);
  assert.equal(Fishing.reelOk(s, s.biteAt - 1), false, '입질 전 E 는 실패');
  assert.equal(Fishing.tickSession(s, s.biteAt), 'bite');
  assert.equal(Fishing.reelOk(s, s.biteAt + 500), true);
  assert.equal(Fishing.tickSession(s, s.biteAt + Fishing.REEL_WINDOW_MS + 1), 'miss');
  assert.equal(Fishing.reelOk(s, s.biteAt + 500), false, '창이 지나면 실패');
  assert.equal(outdoor.interactables.filter((i) => i.kind === 'fish').length, 4);
  for (const f of outdoor.interactables.filter((i) => i.kind === 'fish')) assert.ok(canStand(outdoor, f.x, f.y), '낚시 자리는 설 수 있다');
  const tel = outdoor.interactables.find((i) => i.kind === 'telescope');
  assert.ok(tel && canStand(outdoor, tel.x, tel.y));
});

